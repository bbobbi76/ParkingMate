create table parking_lot (
    id                bigint generated by default as identity primary key,
    code              varchar(40)  not null unique,
    name              varchar(80)  not null,
    category          varchar(20)  not null,
    lat               double precision not null,
    lng               double precision not null,
    coord_source      varchar(120) not null,
    capacity          integer,
    capacity_source   varchar(120),
    operable_capacity integer,
    current_count     integer      not null default 0,
    manual_status     varchar(20)  not null default 'AUTO',
    incentive         boolean      not null default false,
    sensor_enabled    boolean      not null default false,
    shuttle_stop      varchar(40),
    note              varchar(200),
    data_source       varchar(200) not null,
    sort_order        integer      not null default 0,
    updated_at        timestamp with time zone not null,
    version           bigint       not null default 0
);

create table sensor_device (
    id           bigint generated by default as identity primary key,
    device_id    varchar(40) not null unique,
    lot_id       bigint      not null references parking_lot (id),
    gate         varchar(10) not null,
    last_seq     bigint,
    last_seen_at timestamp with time zone
);

create table benefit (
    id          bigint generated by default as identity primary key,
    name        varchar(80)  not null,
    description varchar(300) not null,
    active      boolean      not null default true,
    is_example  boolean      not null default true
);

create table voucher (
    id            bigint generated by default as identity primary key,
    code          varchar(12) not null unique,
    lot_id        bigint      not null references parking_lot (id),
    benefit_id    bigint      not null references benefit (id),
    plate_number  varchar(20) not null,
    festival_date date        not null,
    channel       varchar(10) not null,
    status        varchar(10) not null,
    issued_at     timestamp with time zone not null,
    redeemed_at   timestamp with time zone,
    constraint uk_voucher_plate_day unique (plate_number, festival_date)
);

create table vehicle_event (
    id          bigint generated by default as identity primary key,
    device_id   varchar(40) not null,
    lot_id      bigint      not null references parking_lot (id),
    direction   varchar(3)  not null,
    seq         bigint      not null,
    occurred_at timestamp with time zone not null,
    received_at timestamp with time zone not null,
    voucher_id  bigint references voucher (id),
    constraint uk_event_device_seq unique (device_id, seq)
);
create index ix_event_lot_time on vehicle_event (lot_id, occurred_at);

create table shuttle_route (
    id               bigint generated by default as identity primary key,
    name             varchar(80)  not null,
    days             varchar(30)  not null,
    first_departure  time         not null,
    last_departure   time         not null,
    interval_minutes integer      not null,
    bus_count        integer,
    source           varchar(200) not null
);

create table shuttle_stop (
    id             bigint generated by default as identity primary key,
    route_id       bigint      not null references shuttle_route (id),
    seq            integer     not null,
    name           varchar(40) not null,
    lat            double precision not null,
    lng            double precision not null,
    offset_minutes integer     not null,
    offset_source  varchar(120) not null,
    coord_source   varchar(120) not null
);
