"""STM32 USB + Pico Wi-Fi -> durable laptop queue -> team Spring backend.
No simulated passages are generated by this program.
"""
import argparse
import hmac
import json
import os
import re
import sqlite3
import threading
import time
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
import requests
from bridge_store import Store, DEVICES
from connection import resolve

HERE = Path(__file__).resolve().parent

class Bridge:
    def __init__(self, store, api, key, token='', allow_legacy=False, capture_only=False):
        self.store, self.api, self.key, self.token = store, api.rstrip('/'), key, token
        self.allow_legacy, self.capture_only = allow_legacy, capture_only
        self.serial_session = self.pending_session = None
        self.lock = threading.Lock()
        self.seen = {}
        self.health = {}
        self.stop = threading.Event()
        self.last_heartbeat = 0.0

    def touch(self, device, health=None):
        if device not in DEVICES:
            raise ValueError('Unknown device')
        with self.lock:
            self.seen[device] = time.monotonic()
            if health is not None:
                self.health[device] = health

    def live_devices(self):
        with self.lock:
            return [d for d, at in self.seen.items() if time.monotonic() - at < 12]

    def event(self, device, direction, event_id=None):
        seq, new = self.store.enqueue(device, direction, event_id)
        self.touch(device)
        if new:
            print(f'[received] {device} {direction} seq={seq}', flush=True)
        return seq

    def serial_connected(self):
        # Reconnect requires fresh status before accepting queued frames.
        self.serial_session = self.pending_session = None

    def serial_line(self, line):
        if self.allow_legacy:
            if line == 'IN':
                self.event('entry-stm32', 'IN')
                return None
            if re.fullmatch(r'#STATUS a=[01] b=[01] faults=\d+', line):
                self.touch('entry-stm32', line)
                return None
        try:
            data = json.loads(line)
        except ValueError:
            return None
        if (not isinstance(data, dict) or data.get('device') != 'entry-stm32'
                or type(data.get('protocol')) is not int or data['protocol'] != 3):
            return None
        session = data.get('session')
        if not isinstance(session, str) or (session and not re.fullmatch(r'[0-9a-f]{32}', session)):
            return None
        if data.get('kind') == 'status':
            if any(type(data.get(k)) is not int or data[k] not in (0, 1) for k in ('a', 'b')):
                return None
            self.touch('entry-stm32', {k: data.get(k) for k in ('a', 'b', 'queue', 'dropped', 'faults')})
            if not session:
                if self.pending_session is None:
                    self.pending_session = uuid.uuid4().hex
                self.serial_session = None
                return 'SESSION ' + self.pending_session + '\n'
            self.serial_session, self.pending_session = session, None
            return None
        seq = data.get('seq')
        if (data.get('kind') != 'passage' or data.get('direction') != 'forward'
                or type(seq) is not int or not 1 <= seq <= 0xffffffff or not session
                or session not in (self.serial_session, self.pending_session)):
            return None
        self.event('entry-stm32', 'IN', session + ':' + str(seq))
        # Only after SQLite commit. A lost ACK yields the same record and ACK.
        self.serial_session, self.pending_session = session, None
        return 'ACK %s %d\n' % (session, seq)

    def snapshot(self):
        now = time.monotonic()
        with self.lock:
            devices = {device: {'online': device in self.seen and now - self.seen[device] < 12,
                                'status': self.health.get(device)} for device in DEVICES}
        counts = self.store.counts()
        return {'mode': 'capture_only' if self.capture_only else 'forwarding',
                'pending': counts.get(0, 0), 'delivered': counts.get(1, 0), 'devices': devices}

    def send_once(self, session):
        if self.capture_only:
            return False
        pending = self.store.pending()
        if not pending:
            return False
        row_id, event = pending
        try:
            response = session.post(self.api + '/api/sensor/events', json={'events': [event]},
                                    headers={'X-Sensor-Key': self.key}, timeout=(3, 5), allow_redirects=False)
            try:
                if response.status_code != 200:
                    raise ValueError('HTTP ' + str(response.status_code))
                result = response.json()
            finally:
                response.close()
            if (not isinstance(result, dict) or type(result.get('accepted')) is not int
                    or type(result.get('duplicates')) is not int
                    or result['accepted'] not in (0, 1) or result['duplicates'] not in (0, 1)
                    or result['accepted'] + result['duplicates'] != 1 or result.get('errors') != []):
                raise ValueError('Backend did not confirm this event without errors')
            self.store.delivered(row_id)
            print(f'[delivered] {event["deviceId"]} seq={event["seq"]}', flush=True)
            return True
        except (requests.RequestException, ValueError) as error:
            # HTTP 200 with per-event errors must not delete pending data.
            self.store.failed(row_id, type(error).__name__ + ': ' + str(error))
            print('[retry] Backend has not confirmed the oldest event; queue retained', flush=True)
            return False

    def sender(self):
        if self.capture_only:
            return
        with requests.Session() as session:
            while not self.stop.is_set():
                try:
                    sent = self.send_once(session)
                except sqlite3.Error:
                    print('[storage fault] Sender paused; queue retained', flush=True)
                    sent = False
                if time.monotonic() - self.last_heartbeat >= 5:
                    # Only an actual recent board message permits a heartbeat.
                    for device in self.live_devices():
                        try:
                            response = session.post(self.api + '/api/sensor/heartbeat', json={'deviceId': device},
                                                    headers={'X-Sensor-Key': self.key}, timeout=(2, 3), allow_redirects=False)
                            response.close()
                        except requests.RequestException:
                            pass
                    self.last_heartbeat = time.monotonic()
                self.stop.wait(0.05 if sent else 2)


def make_handler(bridge):
    class Handler(BaseHTTPRequestHandler):
        def setup(self):
            super().setup()
            self.connection.settimeout(4)

        def respond(self, status):
            self.send_response(status)
            self.send_header('Content-Length', '0')
            self.send_header('Connection', 'close')
            self.end_headers()
            self.close_connection = True

        def do_GET(self):
            if self.path != '/health':
                return self.respond(404)
            if bridge.token and not hmac.compare_digest(self.headers.get('X-Bridge-Key', '').encode(), bridge.token.encode()):
                return self.respond(401)
            try:
                raw = json.dumps(bridge.snapshot()).encode()
                self.send_response(200)
                self.send_header('Content-Type', 'application/json')
                self.send_header('Content-Length', str(len(raw)))
                self.send_header('Connection', 'close')
                self.end_headers()
                self.wfile.write(raw)
            except sqlite3.Error:
                self.respond(503)
            except OSError:
                pass
            finally:
                self.close_connection = True

        def do_POST(self):
            if self.path not in ('/event', '/heartbeat'):
                return self.respond(404)
            try:
                if self.headers.get('Transfer-Encoding') or len(self.headers.get_all('Content-Length', [])) != 1:
                    return self.respond(400)
                length = int(self.headers['Content-Length'])
                if not 0 < length <= 2048:
                    return self.respond(413)
                raw = self.rfile.read(length)
                if len(raw) != length:
                    return self.respond(400)
                if bridge.token and not hmac.compare_digest(self.headers.get('X-Bridge-Key', '').encode(), bridge.token.encode()):
                    return self.respond(401)
                body = raw.decode('utf-8')
                if self.path == '/event' and body.strip() == 'OUT':
                    data = {'deviceId': 'exit-pico', 'direction': 'OUT'}
                else:
                    data = json.loads(body)
                if not isinstance(data, dict) or data.get('deviceId') != 'exit-pico':
                    return self.respond(400)
                if self.path == '/event':
                    if 'eventId' in data and data['eventId'] is None:
                        return self.respond(400)
                    if not bridge.allow_legacy and not data.get('eventId'):
                        return self.respond(400)
                    bridge.event(data['deviceId'], data.get('direction'), data.get('eventId'))
                else:
                    # Heartbeat reports board reachability, not physical sensor accuracy.
                    if any(type(data.get(k)) is not int or data[k] not in (0, 1) for k in ('a', 'b')):
                        return self.respond(400)
                    bridge.touch('exit-pico', {k: data.get(k) for k in ('a', 'b', 'queue', 'faults', 'storage_ok', 'dropped', 'link', 'configured')})
                return self.respond(204)
            except (ValueError, TypeError, UnicodeError):
                return self.respond(400)
            except sqlite3.Error:
                return self.respond(503)
            except OSError:
                # Peer timeout/disconnect: a committed event is deduplicated on retry.
                self.close_connection = True

        def log_message(self, *args):
            pass
    return Handler


def serial_reader(bridge, port):
    import serial
    from serial.tools import list_ports
    while not bridge.stop.is_set():
        selected = port
        if port.lower() == 'auto':
            ports = [p.device for p in list_ports.comports() if p.vid == 0x0483 and p.pid == 0x374B]
            selected = ports[0] if len(ports) == 1 else None
        if not selected:
            bridge.stop.wait(2)
            continue
        try:
            with serial.Serial(selected, 115200, timeout=0.1, write_timeout=1) as connection:
                bridge.serial_connected()
                print('[serial] Connected: ' + selected, flush=True)
                buffer, discarding = bytearray(), False
                while not bridge.stop.is_set():
                    for byte in connection.read(256):
                        if byte == 10:
                            if not discarding:
                                command = bridge.serial_line(buffer.decode('ascii', errors='replace').rstrip('\r'))
                                if command:
                                    connection.write(command.encode('ascii'))
                            buffer.clear(); discarding = False
                        elif not discarding:
                            if len(buffer) >= 512:
                                buffer.clear(); discarding = True
                            else:
                                buffer.append(byte)
        except (serial.SerialException, OSError, sqlite3.Error) as error:
            print('[serial unavailable] ' + type(error).__name__, flush=True)
            bridge.stop.wait(2)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--api')
    parser.add_argument('--key')
    parser.add_argument('--config', type=Path)
    parser.add_argument('--capture-only', action='store_true', help='Save and ACK board events without sending events or heartbeats to a backend')
    parser.add_argument('--allow-legacy', action='store_true', help='Explicitly allow old ID-less IN/OUT messages (no retry deduplication)')
    parser.add_argument('--serial', help='STM32 port, e.g. COM7, or auto; omit for Pico only')
    parser.add_argument('--entry-device', choices=['entry-stm32'], default='entry-stm32')
    parser.add_argument('--http-host', default='0.0.0.0')
    parser.add_argument('--http-port', type=int, default=9000)
    parser.add_argument('--state-dir', type=Path, default=HERE / 'runtime')
    args = parser.parse_args()
    try:
        api, key = ('', '') if args.capture_only else resolve(args.api, args.key, args.config)
    except (ValueError, OSError) as error:
        parser.error(str(error))
    store = Store(args.state_dir / 'bridge.sqlite', api or None)
    try:
        store.import_legacy(HERE)
        bridge = Bridge(store, api, key, os.environ.get('BRIDGE_TOKEN', ''), args.allow_legacy, args.capture_only)
        server = ThreadingHTTPServer((args.http_host, args.http_port), make_handler(bridge))
        workers = [] if args.capture_only else [threading.Thread(target=bridge.sender, daemon=True)]
        if args.serial:
            workers.append(threading.Thread(target=serial_reader, args=(bridge, args.serial), daemon=True))
        for worker in workers:
            worker.start()
        print(f'[bridge] http://{args.http_host}:{args.http_port}/event -> {api or "LOCAL CAPTURE ONLY"}', flush=True)
        print('[bridge] STM32 protocol 3 / Pico eventId; ACK means saved on laptop.', flush=True)
        if args.allow_legacy:
            print('[legacy] ID-less input enabled; those messages cannot be deduplicated.', flush=True)
        try:
            server.serve_forever(poll_interval=0.25)
        except KeyboardInterrupt:
            pass
        finally:
            bridge.stop.set()
            server.server_close()
            for worker in workers:
                worker.join(timeout=15)
    finally:
        store.close()

if __name__ == '__main__':
    main()
